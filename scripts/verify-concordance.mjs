import fs from "node:fs";
import assert from "node:assert/strict";
import {crosswalkNumber,groupedWitnessEntries,SOURCE_FRAGMENT_COUNTS,WITNESS_ENTRY_COUNTS} from "../data/concordance.js";
const volumes=[1,2,3].map(i=>JSON.parse(fs.readFileSync("data/volume-"+i+".json","utf8")));
const entries=volumes.flatMap(v=>v.entries);
assert.deepEqual(volumes.map(v=>v.entries.length),SOURCE_FRAGMENT_COUNTS);
assert.deepEqual(WITNESS_ENTRY_COUNTS,[129,71,142]);
const groups=groupedWitnessEntries(entries);
assert.equal(groups.size,342);
for(let i=1;i<=342;i++)assert.equal(groups.get(i)?.length,i===317?2:1,"witness "+i);
assert.equal(crosswalkNumber(85),86);
assert.equal(crosswalkNumber(86),85);
assert.equal(crosswalkNumber(318),317);
assert.equal(crosswalkNumber(319),318);
assert.equal(crosswalkNumber(343),342);
assert.match(entries[316].text,/博学于文/);
assert.match(entries[317].text,/先儒解/);
assert.match(entries[318].text,/众人只说/);
console.log("PASS 343 legacy fragments mapped to 342 Wikisource reference numbers (not textual collation)");
